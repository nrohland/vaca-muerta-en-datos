import {test,expect} from './browser-fixtures';
import AxeBuilder from '@axe-core/playwright';
import {readFileSync} from 'node:fs';
import {validateRelease} from '../lib/contract';
import {validatePrices} from '../lib/metrics';
import {operatorRanking} from '../lib/operator-analysis';
const release=validateRelease(JSON.parse(readFileSync('public/data/release.json','utf8')));
const prices=validatePrices(JSON.parse(readFileSync('public/data/prices.json','utf8')));
const period='2026-08-01';
const base=`/vaca-muerta-pulse/?tab=operators&month=${period}`;
test('complete ranking filters without changing total share and supports URL drill-down/back',async({page})=>{
 await page.goto(base);
 const current=release.production.find(r=>r.fluid==='oil'&&r.periodo===period)!;
 const entries=operatorRanking(release.entities,current,prices,'volume','yoy');
 await expect(page.locator('.operators-ranking-list > li')).toHaveCount(entries.length);
 await page.getByRole('searchbox',{name:'Buscar operador'}).fill('YPF');
 await expect(page.locator('.operators-ranking-list > li')).toHaveCount(1);
 await page.locator('.operators-ranking-list button').click();
 await expect(page).toHaveURL(/operator=YPF/);
 await expect(page.locator('.operators-heading h1')).toHaveText('YPF S.A.');
 await expect(page.locator('.operators-data tbody tr')).toHaveCount(36);
 await page.locator('.operators-evolution .ranges button',{hasText:'12m'}).click();
 await expect(page.locator('.operators-data tbody tr')).toHaveCount(12);
 await page.getByRole('button',{name:'← Todos los operadores'}).click();
 await expect(page).not.toHaveURL(/operator=YPF/);
 await expect(page.getByRole('searchbox',{name:'Buscar operador'})).toHaveValue('YPF');
 await expect(page.locator('.operators-ranking-list > li')).toHaveCount(1);
 await page.getByRole('searchbox',{name:'Buscar operador'}).fill('nothing matches this operator');
 await expect(page.locator('.operators-empty')).toBeVisible();
 await page.getByRole('button',{name:'Restablecer filtros'}).click();
 await expect(page.locator('.operators-ranking-list > li')).toHaveCount(entries.length);
});
test('gas USD uses warehouse values and English detail survives reload',async({page})=>{
 await page.goto(base+'&fluid=gas&mode=value&comparison=mom&operator=YPF');
 await expect(page.locator('.operators-dashboard')).toBeVisible();
 await expect(page.locator('.operators-dashboard .kpi-card--primary .kpi-back')).toContainText('Henry Hub');
 await expect(page.locator('.operators-dashboard .kpi-card--primary .kpi-value')).toContainText('USD');
 await page.getByRole('button',{name:'English',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Operator data',exact:true})).toBeVisible();
 await expect(page.locator('.operators-dashboard .kpi-card--primary .kpi-back')).toContainText('Henry Hub');
 await page.reload();
 await expect(page.getByRole('heading',{name:'Operator data',exact:true})).toBeVisible();
 await expect(page).toHaveURL(/operator=YPF/);
});
test('operators remain accessible and fit mobile without document overflow',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 await page.goto(base);
 await expect(page.locator('.operators-ranking-list > li').first()).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 expect(await page.evaluate(()=>document.documentElement.scrollHeight<=Math.max(innerHeight,document.body.scrollHeight)+2)).toBe(true);
 const listBox=(await page.locator('.operators-ranking-list').boundingBox())!;
 const noteBox=(await page.locator('.operators-ranking > .chart-context').boundingBox())!;
 expect(noteBox.y).toBeGreaterThanOrEqual(listBox.y+listBox.height);
 const overview=await new AxeBuilder({page}).include('.operators-dashboard').analyze();
 expect(overview.violations.filter(v=>['critical','serious'].includes(v.impact??''))).toEqual([]);
 await page.locator('.operators-ranking-list button').first().click();
 await expect(page.locator('.operators-data')).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 const detail=await new AxeBuilder({page}).include('.operators-dashboard').analyze();
 expect(detail.violations.filter(v=>['critical','serious'].includes(v.impact??''))).toEqual([]);
});
